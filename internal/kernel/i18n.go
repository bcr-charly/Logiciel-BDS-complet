// Lang extrait la langue de la requête : cookie, ?lang=, puis Accept-Language.
func Lang(r *http.Request) string {
	if c, err := r.Cookie(LangCookie); err == nil && (c.Value == LangFR || c.Value == LangEN) {
		return c.Value
	}
	if l := r.URL.Query().Get("lang"); l == LangFR || l == LangEN {
		return l
	}
	accept := r.Header.Get("Accept-Language")
	if strings.HasPrefix(accept, "en") {
		return LangEN
	}
	return LangFR
}

// T traduit une clé dans la langue donnée, avec args fmt-style si fournis.
func T(lang, key string, args ...any) string {
	tbl := tables[lang]
	if tbl == nil {
		tbl = tables[LangFR]
	}
	s, ok := tbl[key]
	if !ok {
		s = tables[LangFR][key]
	}
	if s == "" {
		return key
	}
	if len(args) > 0 {
		return fmt.Sprintf(s, args...)
	}
	return s
}

// Langues retourne les langues disponibles.
func Langues() []string { return []string{LangFR, LangEN} }
